import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
import {chromium} from 'playwright-core';
import {mkdtemp,stat,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';
const workspace=await mkdtemp(join(tmpdir(),'craft-editor-smoke-'));
const client=new Client({name:'craft-editor-smoke',version:'1'});
let browser;
try {
 await client.connect(new StdioClientTransport({command:process.execPath,args:[resolve('dist/adapter.mjs')],env:{...process.env,CRAFT_WORKSPACE_ROOT:workspace},stderr:'inherit'}));
 const listed=await client.listTools();assert(listed.tools.some(t=>t.name==='open_browser_editor'));
 const opened=await client.callTool({name:'open_browser_editor',arguments:{}});
 assert(!opened.isError,JSON.stringify(opened));
 const url=opened.structuredContent.editorUrl;
 assert.equal((await fetch(new URL('/bad/',url))).status,403);
 browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader','--use-angle=swiftshader']});
 const page=await browser.newPage({viewport:{width:1280,height:1024}});
 page.on('pageerror',e=>console.error('PAGE',e.message));
 await page.goto(url);
  await page.waitForTimeout(1000);
 const frame=page.frames().find(f=>f.url().includes('/panel'));
 await frame.waitForFunction(()=>window.__craftPlugin?.automationReady,{},{timeout:120000});
 const status=await client.callTool({name:'editor_status',arguments:{}});assert.equal(status.structuredContent.attached,true);
 const reopened=await client.callTool({name:'open_browser_editor',arguments:{}});assert.deepEqual(reopened.structuredContent.runtime,opened.structuredContent.runtime);assert.equal(reopened.structuredContent.editorUrl,url);
 const rejected=await client.callTool({name:'open_browser_editor',arguments:{workspace:'/tmp'}});assert.equal(rejected.isError,true);
 const call=async(name,args={})=>{const r=await client.callTool({name,arguments:args},undefined,{timeout:180000});assert(!r.isError,JSON.stringify(r));return r;};
 await call('doc_new',{width:64,height:48,name:'Adapter roundtrip',background:'white'});
 await call('command_run',{id:'layer.new.layer',params:{name:'Restoration layer'}});
 assert.match(JSON.stringify(await call('doc_inspect')),/Restoration layer/);
 await call('doc_save',{path:'photo.pcraft'});
 await call('doc_close');
 await call('doc_open',{path:'photo.pcraft'});
 assert.match(JSON.stringify(await call('doc_inspect')),/Restoration layer/);
 await call('doc_export',{path:'photo.png'});
 assert((await stat(join(workspace,'photo.png'))).size>50);
 console.log(JSON.stringify({workspace,roundtrip:true,tools:listed.tools.length,editorReady:true,status:status.structuredContent}));
 await page.reload();
 await page.waitForTimeout(1500);
 const reloaded=page.frames().find(f=>f.url().includes('/panel'));
 await reloaded.waitForFunction(()=>window.__craftPlugin?.automationReady,{},{timeout:120000});
 await call('doc_open',{path:'photo.pcraft'});
 assert.match(JSON.stringify(await call('doc_inspect')),/Restoration layer/);
 await page.screenshot({path:join(workspace,'editor.png')});
 await page.goto('about:blank');
 await page.waitForTimeout(500);
 assert.equal((await client.callTool({name:'editor_status',arguments:{}})).structuredContent.attached,false);
 console.log('reload and detach PASS');
 await writeFile(join(workspace,'result.json'),JSON.stringify({editorReady:true,tools:listed.tools.length}));
} finally {await browser?.close();await client.close();}
